export interface IEmailUpdate extends Document {
  subject: string;
  /** Markdown content — the canonical source for both plain-text and HTML rendering. */
  content: string;
  /** Rendered HTML derived from `content` (populated when the draft is created/updated). */
  renderedHtml?: string;
  context?: string;
  type: "update" | "promotional" | "security" | "general";
  links?: { label: string; url: string }[];
  status: "draft" | "approved" | "sent" | "rejected";
  /** True when the content was generated by the AI rather than manually authored. */
  isAiGenerated: boolean;
  /**
   * Entity reference strings that were resolved during AI generation.
   * Format: "/<collection>/<id>", e.g. "/institutions/64abc123".
   * Useful for auditing what data fed the generation.
   */
  aiContextRefs?: string[];
  /** User who requested the AI generation (or manual creator). */
  requestedBy?: Types.ObjectId;
  /** Admin/moderator who approved the draft for sending. */
  approvedBy?: Types.ObjectId;
  approvedAt?: Date;
  /** Admin/moderator who rejected the draft. */
  rejectedBy?: Types.ObjectId;
  rejectedAt?: Date;
  rejectionReason?: string;
  sentAt?: Date;
  createdAt: Date;
  updatedAt: Date;
}
