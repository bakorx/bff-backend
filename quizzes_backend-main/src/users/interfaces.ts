export interface IUser extends Document {
  username: string;
  email: string;
  password?: string;
  authKey?: string;
  name: string;
  studentId?: string;
  bio?: string;
  role: "student" | "creator" | "moderator" | "super_admin";
  isBanned: boolean;
  /** True once the user proves ownership of `email` — set automatically for OAuth-created users, manually after a verification email for legacy accounts. */
  emailVerified: boolean;
  /** Linked OAuth identities. Same email can map to multiple providers; same provider is idempotent on `providerUserId`. */
  linkedProviders: ILinkedProvider[];
  accessType: "quiz" | "course" | "duration" | "default";
  isSubscribed: boolean;
  hasFreeAccess: boolean;
  freeAccessCount: number;
  lastLogin: Date;
  isDeleted: boolean;
  yearOfStudy?: number;
  preferredPersonaId?: Types.ObjectId;
  // --- New monetisation fields ---
  planTier: PlanTier | null;
  planDuration: PlanDuration | null;
  dailyUsage: IDailyUsage;
  credits: IUserCredits;
  referralCode: string;
  referredBy: Types.ObjectId | null;
  pendingReferralDiscount: boolean;
  studentVerification: IStudentVerification;
  streak: IStreak;
  loyaltyDiscount: ILoyaltyDiscount;
  // --- Deprecated (kept for backward compat) ---
  /** @deprecated Use credits.balance instead */
  quizCredits: number;
  /** @deprecated Use credits.balance instead */
  aiUsageStats: {
    totalCreditsUsed: number;
    creditsRemaining: number;
    lastRechargeDate: Date;
    monthlyUsage: Record<string, number>;
    questionsAsked: number;
    explanationsRequested: number;
  };
  notificationSettings?: INotificationSettings;
  /** refs to IStudentEnrolment */
  enrolments?: Types.ObjectId[];
  primaryEnrolmentId?: Types.ObjectId;
  programSubscriptions?: Types.ObjectId[];
  profilePicture?: Types.ObjectId | IUpload;
  /**
   * Foreign URL of the user's profile picture as last returned by an OAuth
   * provider (Google, GitHub). Stored separately from `profilePicture`
   * (which is a Qz upload) so a custom upload always wins. Set on OAuth
   * signup; on auto-link, set only when the user has no `profilePicture`.
   */
  oauthPicture?: string;
  passwordChangedAt?: Date;
  /** Last time we sent this user a `email:weekly_digest` job. Used by the digest handler as an idempotency guard so retries / replays within the same week don't double-send. */
  lastDigestSentAt?: Date | null;
  onboarding: IOnboarding;
}

// ---------------------------------------------------------------------------
// Notification document
//
// Index recommendations:
//   { userId: 1, read: 1 }
//   { userId: 1, type: 1 }
//   { scheduledFor: 1, fired: 1 }   ← for the scheduler sweep
// ---------------------------------------------------------------------------

export type NotificationType =
  | "exam_reminder"
  | "quiz_available"
  | "study_partner_request"
  | "study_partner_message"
  | "course_announcement"
  | "recommendation_update"
  | "approval_status_change"
  | "newsletter"
  | "security_alert"
  | "account_activity"
  | "system_update"
  | "program_offering_available"
  | "timetable_change"
  | "urgent_timetable_alert";

export interface INotification extends Document {
  userId: Types.ObjectId;
  type: NotificationType;
  /** If true the notification was triggered by a system event and cannot be suppressed by user settings. */
  isSystemNotification: boolean;
  /** Which delivery channels this notification was (or will be) sent on. */
  channels: { email: boolean; inApp: boolean; push: boolean };
  title: string;
  body: string;
  /** Flexible context payload — e.g. { courseId, examDate, quizId, contentType }. */
  metadata?: Record<string, unknown>;
  read: boolean;
  readAt?: Date;
  /** Set for scheduled notifications (e.g. exam reminders). */
  scheduledFor?: Date;
  sentAt?: Date;
  failed: boolean;
  failureReason?: string;
  createdAt: Date;
}

