/** Per-channel delivery switches for a single notification category. */
export interface INotificationChannels {
  email: boolean;
  inApp: boolean;
  push: boolean;
}

/**
 * User-controlled notification preferences.
 *
 * Toggleable categories — user can enable/disable per channel.
 * System categories — always sent; the flags are informational only.
 */
export interface INotificationSettings {
  // --- User-toggleable ---
  examReminders: INotificationChannels & {
    /** Days before the exam to send a reminder. User may pick multiple. Default [3, 1]. */
    reminderIntervals: Array<7 | 3 | 1>;
  };
  quizAvailability: INotificationChannels;
  studyPartnerActivity: INotificationChannels;
  courseAnnouncements: INotificationChannels;
  recommendationUpdates: INotificationChannels;
  /** Relevant for staff/admin roles — approval workflow events. */
  approvalStatusChanges: INotificationChannels;
  newsletter: INotificationChannels;

  // --- System / non-negotiable (user cannot disable) ---
  securityAlerts: INotificationChannels;
  accountActivity: INotificationChannels;
  systemUpdates: INotificationChannels;

  // --- Weekly study digest (opt-in) ---
  weeklyDigest: boolean;
}

